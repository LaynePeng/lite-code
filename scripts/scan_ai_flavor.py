# -*- coding: utf-8 -*-
"""扫描教程中的"AI 味"特征词/句式，输出 文件:行号:内容。"""
import os
import re

BOOK = "AI-Coding-Agent-Dummy-Book"

# (模式, 说明)
PATTERNS = [
    (r"总而言之|总的来说|综上所?述|总结一下|一句话总结", "总结套话"),
    (r"让我们|我们(?:一起|来|现在|先)", "祈使引导"),
    (r"值得注意的是|需要注意的是|需要指出的是|值得一提的是", "提醒套话"),
    (r"首先[，,]|其次[，,]|最后[，,]|第一[，,].*第二[，,]", "模板排比"),
    (r"强大的|惊艳|令人惊叹|叹为观止|无与伦比|无敌|神器|杀手锏", "夸张形容"),
    (r"一站式|保姆级|干货满满|满满的干货|闭眼入|抄作业", "营销腔"),
    (r"相信你|你会发现|你将学会|你可能会问|你可能会想|想象一下|试想一下", "读者代入"),
    (r"简单来说|说白了|话虽如此|话说回来", "口语化"),
    (r"赋能|抓手|闭环|颗粒度|底层逻辑|心智|对齐|打通", "黑话"),
    (r"不仅仅?是.{0,20}更是|不仅是.{0,20}更是|不只是.{0,20}而是", "排比强调"),
    (r"在.{0,20}(?:的)?(?:今天|时代|当下|背景)[，,]", "时代背景腔"),
    (r"一切|所有的一切|所有的", "绝对化"),
    (r"极致|完美|完美地|丝滑|优雅地|漂亮地", "修饰过度"),
    (r"你(?:可以|需要|应该|必须|要)记住|记住[，,]", "说教"),
    (r"等等[，,]|好吧[，,]|对了[，,]|嗯[，,]|哈哈|嘿嘿", "口语拟声"),
    (r"进行一个|进行.{0,6}的操作|做一次.{0,6}的处理", "翻译腔"),
    (r"这(?:就|才)是.{0,20}(?:的)?(?:精髓|本质|意义|价值)", "升华腔"),
    (r"核心要点|关键点在于|关键在于", "冗余强调"),
    (r"让我们一起|一起(?:来|动手|探索|学习)", "陪伴腔"),
    (r"[！！]{2,}|!!!|！！！", "感叹号连用"),
    (r"✨|🔥|💡|🎯|🚀|✅|📌|⚠️|💪|🎉", "emoji"),
    (r"其实[，,]|本质上[，,]|说白了", "口头禅"),
    (r"真正地|真正地做到|真正的", "强调冗余"),
]

def scan():
    hits = []
    for fn in sorted(os.listdir(BOOK)):
        if not fn.endswith(".md"):
            continue
        path = os.path.join(BOOK, fn)
        with open(path, encoding="utf-8") as f:
            for i, line in enumerate(f, 1):
                for pat, label in PATTERNS:
                    if re.search(pat, line):
                        hits.append((fn, i, label, line.rstrip()[:120]))
                        break
    for fn, i, label, text in hits:
        print(f"{fn}:{i} [{label}] {text}")

if __name__ == "__main__":
    scan()
